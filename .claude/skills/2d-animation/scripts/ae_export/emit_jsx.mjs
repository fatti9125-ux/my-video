/**
 * Write the After Effects build script (.jsx, ExtendScript / ES3) for one part from layers.json (walk.tsx),
 * and copy every referenced footage file into the package folder.
 * Usage: node emit_jsx.mjs <layers.json> <package_dir> "<Comp Name>"
 * Package layout: <pkg>/<Name>.jsx, footage/ (sprites, rig parts, BG.mp4, FX/ png sequence), audio/ (VO + SFX), fonts/.
 */
import fs from "fs";
import path from "path";

const [, , layersPath, pkg, compName] = process.argv;
const L = JSON.parse(fs.readFileSync(layersPath, "utf8"));
const FPS = 30, W = 1920, H = 1080, INK = [29 / 255, 23 / 255, 18 / 255];
const copy = (rel, from = `public/${rel}`) => {
  const dst = path.join(pkg, "footage", rel);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  if (!fs.existsSync(dst)) fs.copyFileSync(from, dst);
  return `footage/${rel}`;
};
const hex = (c) => { const h = c.replace("#", ""); const n = h.length === 3 ? h.split("").map((x) => x + x).join("") : h; return [0, 2, 4].map((i) => +(parseInt(n.slice(i, i + 2), 16) / 255).toFixed(4)); };
const J = (v) => JSON.stringify(v);
const db = (v) => +(20 * Math.log10(Math.max(v, 1e-4))).toFixed(2);
const r2 = (v) => +(+v).toFixed(2);

const out = [];
const w = (s) => out.push(s);
w(`// ${compName}: After Effects rebuild script (generated by scripts/ae_export, do not hand-edit; re-export instead).
// HOW TO USE: unzip the package anywhere, install fonts/Montserrat-ExtraBold.ttf, then in After Effects:
// File > Scripts > Run Script File... and pick this .jsx. It imports all footage and builds the comp
// "${compName}" with every character, rig limb, caption, label, camera move, the voiceover and each SFX
// as its own editable layer. Backgrounds/graphics = BG.mp4 segments, drawn FX = FX png sequence.
(function () {
var ROOT = File($.fileName).parent.fsName;
app.beginUndoGroup("Build ${compName}");
var proj = app.project || app.newProject();
var folder = proj.items.addFolder("${compName} footage");
var comp = proj.items.addComp("${compName}", ${W}, ${H}, 1, ${L.dur / FPS}, ${FPS});
comp.parentFolder = folder;
var cache = {};
function F(rel, seq) {
  if (cache[rel]) return cache[rel];
  var io = new ImportOptions(new File(ROOT + "/" + rel));
  if (seq) { io.sequence = true; io.forceAlphabetical = true; }
  var it = proj.importFile(io); it.parentFolder = folder;
  if (seq) { it.mainSource.conformFrameRate = ${FPS}; it.mainSource.alphaMode = AlphaMode.STRAIGHT; }
  cache[rel] = it; return it;
}
function T(f) { return f / ${FPS}; }
function add(item, a, b, name) { var l = comp.layers.add(item); l.startTime = 0; l.inPoint = T(a); l.outPoint = T(b); if (name) l.name = name; return l; }
function nul(name, a, b, pos) { var n = comp.layers.addNull(); n.name = name; n.inPoint = T(a); n.outPoint = T(b);
  n.transform.anchorPoint.setValue([0, 0]); n.transform.position.setValue(pos); n.enabled = false; return n; }
function key(p, f, v, hold) { p.setValueAtTime(T(f), v); var k = p.nearestKeyIndex(T(f)); if (hold) p.setInterpolationTypeAtKey(k, KeyframeInterpolationType.HOLD); return k; }
function easeOut(p, k) { var d = p.value instanceof Array ? p.value.length : 1; var e = []; for (var i = 0; i < (p.propertyValueType == PropertyValueType.TwoD_SPATIAL || p.propertyValueType == PropertyValueType.ThreeD_SPATIAL ? 1 : d); i++) e.push(new KeyframeEase(0, 85));
  p.setTemporalEaseAtKey(k, e, e); }
function txt(str, size, fill, strokeW) { var l = comp.layers.addText(str); var sp = l.property("Source Text"); var d = sp.value;
  d.resetCharStyle(); d.fontSize = size; d.fillColor = fill; try { d.font = "Montserrat-ExtraBold"; } catch (e) {}
  d.applyFill = true; if (strokeW) { d.applyStroke = true; d.strokeColor = [0, 0, 0]; d.strokeWidth = strokeW; d.strokeOverFill = false; } else d.applyStroke = false;
  d.justification = ParagraphJustification.CENTER_JUSTIFY; sp.setValue(d); return l; }
function shadow(l) { var s = l.property("ADBE Effect Parade").addProperty("ADBE Drop Shadow"); s.property("ADBE Drop Shadow-0002").setValue(55 * 2.55);
  s.property("ADBE Drop Shadow-0004").setValue(6); s.property("ADBE Drop Shadow-0005").setValue(14); }
`);

// ---------- audio (bottom of the stack) ----------
const vo = copy(`tg2/vo/${L.vo}.mp3`);
w(`add(F(${J(vo)}), 0, ${L.dur}, "VO ${L.vo}");`);
const ends = {};
for (const s of L.sfx) {
  const f = copy(`tg2/sfx/${s.name}.wav`);
  w(`(function(){ var l = comp.layers.add(F(${J(f)})); l.name = "SFX ${s.name} @${s.f}"; l.startTime = T(${s.f});
  l.property("ADBE Audio Group").property("ADBE Audio Levels").setValue([${db(s.vol)}, ${db(s.vol)}]); })();`);
}

// ---------- cameras: one null per Cam (nested for punch-ins); children are expressed in its space ----------
// Remotion Cam = scale(s) about transform-origin O.  AE: null at O, anchor 0, scale keys -> same.
const camO = {};    // cam id -> origin used for its children
w(`var CAM = {};`);
for (const c of L.cams) {
  const [a, b] = c.win;
  const parentO = c.parent === null ? [0, 0] : camO[c.parent];
  w(`CAM[${c.id}] = nul("CAM shot ${c.shot}", ${a}, ${b}, ${J([r2(c.ox - parentO[0]), r2(c.oy - parentO[1])])});`);
  if (c.parent !== null) w(`CAM[${c.id}].setParentWithJump(CAM[${c.parent}]);`);
  let o = [c.ox, c.oy];
  if (c.punch) {
    w(`CAM[${c.id}+"p"] = nul("PUNCH shot ${c.shot}", ${a}, ${b}, ${J([r2(c.punch.ox - c.ox), r2(c.punch.oy - c.oy)])}); CAM[${c.id}+"p"].setParentWithJump(CAM[${c.id}]);`);
    o = [c.punch.ox, c.punch.oy];
  }
  camO[c.id] = o;
  // slow push (linear from->to over dur, then held) + emphasis punch (cubic ease-out)
  w(`(function(){ var s = CAM[${c.id}].transform.scale; key(s, ${c.s0}, [${r2(c.from * 100)}, ${r2(c.from * 100)}]); key(s, ${c.s0 + c.dur}, [${r2(c.to * 100)}, ${r2(c.to * 100)}]);`
    + (c.punch ? ` var p = CAM[${c.id}+"p"].transform.scale; key(p, ${c.punch.at}, [100,100]); easeOut(p, key(p, ${c.punch.at}, [100,100])); key(p, ${c.punch.at + c.punch.frames}, [${r2(c.punch.to * 100)}, ${r2(c.punch.to * 100)}]);` : "") + ` })();`);
}
const camRef = (id) => (id === null ? null : L.cams.find((c) => c.id === id).punch ? `CAM[${id}+"p"]` : `CAM[${id}]`);
const local = (id, x, y) => { const o = id === null ? [0, 0] : camO[id]; return [r2(x - o[0]), r2(y - o[1])]; };

// ---------- BG plates + FX overlay, cut per camera window (so the camera null moves them too) ----------
fs.mkdirSync(path.join(pkg, "footage"), { recursive: true });
const segs = [];
for (const sh of L.shots) {
  const cams = L.cams.filter((c) => c.shot === sh.i && c.parent === null).sort((p, q) => p.win[0] - q.win[0]);
  let cur = sh.s0;
  for (const c of cams) { if (c.win[0] > cur) segs.push({ a: cur, b: c.win[0], cam: null }); segs.push({ a: c.win[0], b: c.win[1], cam: c.id }); cur = c.win[1]; }
  if (cur < sh.s1) segs.push({ a: cur, b: sh.s1, cam: null });
}
const parentTo = (lv, cam) => (cam === null ? "" : `${lv}.setParentWithJump(${camRef(cam)});`);
for (const s of segs) w(`(function(){ var l = add(F("footage/BG.mp4"), ${s.a}, ${s.b}, "BG ${s.a}"); l.transform.anchorPoint.setValue(${J(local(s.cam, 0, 0).map((v) => -v))}); l.transform.position.setValue([0,0]); ${parentTo("l", s.cam)} })();`);

// ---------- native layers, back to front in the order they were drawn ----------
const camKeys = [];
const body = [];
for (const l of L.layers.sort((p, q) => p.z - q.z)) {
  const [a, b] = l.win;
  if (l.kind === "spr") {
    const f = copy(l.file);
    const [x0, y0, x1, y1] = l.meta, k = l.h / (y1 - y0), cx = (x0 + x1) / 2;
    const P = local(l.cam, l.x, l.y);
    body.push(`(function(){ var l = add(F(${J(f)}), ${a}, ${b}, ${J(l.name)});
  l.transform.anchorPoint.setValue([${cx}, ${y1}]); l.transform.position.setValue(${J(P)}); l.transform.scale.setValue([${r2((l.flip ? -1 : 1) * k * 100)}, ${r2(k * 100)}]);
  ${parentTo("l", l.cam)}
  l.transform.rotation.expression = "Math.sin((timeToFrames(time) - ${l.s0}) / 37 + ${l.x}) * 0.5";
  l.transform.scale.expression = "var f = timeToFrames(time) - ${l.s0}; [value[0], value[1] * (1 + Math.sin(f / 19) * 0.005)]";`);
    const pos = "l.transform.position";
    if (l.enter && (l.enter.from === "left" || l.enter.from === "right" || l.enter.from === "top" || l.enter.from === "bottom")) {
      const d = l.enter.dist ?? 1200;
      const off = l.enter.from === "left" ? [-d, 0] : l.enter.from === "right" ? [d, 0] : l.enter.from === "top" ? [0, -d] : [0, l.h * 1.1];
      body.push(`  easeOut(${pos}, key(${pos}, ${l.at}, ${J([r2(P[0] + off[0]), r2(P[1] + off[1])])})); key(${pos}, ${l.at + l.enter.frames}, ${J(P)});`);
    }
    if (l.drop) body.push(`  easeOut(${pos}, key(${pos}, ${l.at}, ${J([P[0], r2(P[1] - l.drop.height)])})); key(${pos}, ${l.at + l.drop.frames}, ${J(P)});`);
    if (l.walk) body.push(`  key(${pos}, ${a}, ${J([r2(P[0] + l.walk * (a - l.at)), P[1]])}); key(${pos}, ${b}, ${J([r2(P[0] + l.walk * (b - l.at)), P[1]])});`);
    if (l.shake) body.push(`  ${pos}.expression = "var f = timeToFrames(time); value + [Math.sin(f * 2.3) * ${l.shake}, Math.cos(f * 3.1) * ${l.shake * 0.4}]";`);
    if (l.alt) {
      // Quill's open-beak drawing: same size/registration as the closed one, swapped on held 3-5 f blocks
      const af = copy(l.alt.file);
      body.push(`  (function(){ var o = add(F(${J(af)}), ${a}, ${b}, ${J("beak open " + l.name)}); o.transform.anchorPoint.setValue([0,0]); o.setParentWithJump(l);
    o.transform.position.setValue([0,0]); o.transform.scale.setValue([100,100]); o.transform.rotation.setValue(0); var op = o.transform.opacity, bp = l.transform.opacity;`);
      let prev = -1;
      l.alt.open.forEach((v, j) => { if (v !== prev) { body.push(`    key(op, ${l.alt.from + j}, ${v ? 100 : 0}, true); key(bp, ${l.alt.from + j}, ${v ? 0 : 100}, true);`); prev = v; } });
      body.push(`  })();`);
    }
    if (l.heads) {
      // Quill: neutral/expression head + open-beak head, parented to the body, beak open on held 3-5 f blocks
      l.heads.forEach((h, i) => {
        const hf = copy(h.file);
        const [hx, hy, hw, hh] = h.rect;
        body.push(`  (function(){ var hd = add(F(${J(hf)}), ${a}, ${b}, ${J((i ? "beak open " : "head ") + l.name)}); hd.transform.anchorPoint.setValue([0,0]);
    hd.setParentWithJump(l); hd.transform.position.setValue([${hx}, ${hy}]); hd.transform.scale.setValue([${r2((hw / h.wh[0]) * 100)}, ${r2((hh / h.wh[1]) * 100)}]); hd.transform.rotation.setValue(0);
    var op = hd.transform.opacity;`);
        let prev = -1;
        l.open.forEach((o, j) => { const v = i === 0 ? (o ? 0 : 100) : (o ? 100 : 0); if (v !== prev) { body.push(`    key(op, ${l.openFrom + j}, ${v}, true);`); prev = v; } });
        if (!l.open.length) body.push(`    op.setValue(${i === 0 ? 100 : 0});`);
        body.push(`  })();`);
      });
    }
    body.push(`})();`);
  } else if (l.kind === "rig") {
    const r = l.rig, [x0, y0, x1, y1] = l.meta, k = l.h / (y1 - y0), cx = (x0 + x1) / 2;
    const legs = r.limbs.filter((q) => q.kind === "leg"), arms = r.limbs.filter((q) => q.kind === "arm");
    const Lg = legs.length ? Math.max(...legs.map((q) => q.len)) : 0;
    const stride = 2 * Lg * Math.sin((17 * Math.PI) / 180);
    const v = l.walk === 0 ? 0 : Math.sign(l.walk) * Math.abs(l.walk) * (stride * k / 16);
    const stop = l.walkUntil === null ? 1e9 : l.walkUntil - l.at;
    const P = local(l.cam, l.x, l.y);
    const wk = l.walk !== 0;
    const lfE = `var lf = timeToFrames(time) - ${l.at}; var walking = ${wk} && lf < ${stop}; var th = walking ? 17 * Math.sin(2 * Math.PI * lf / 32) : 0;`;
    body.push(`(function(){ var rig = nul(${J("RIG " + l.name)}, ${a}, ${b}, ${J(P)}); ${parentTo("rig", l.cam)}
  rig.transform.scale.setValue([${r2((l.flip ? -1 : 1) * k * 100)}, ${r2(k * 100)}]);
  rig.transform.position.expression = "var lf = timeToFrames(time) - ${l.at}; var tW = ${wk} ? Math.min(Math.max(lf, 0), ${stop}) : 0; value + [${r2(v)} * tW, 0]";
  rig.transform.rotation.expression = "var lf = timeToFrames(time) - ${l.at}; (${wk} && lf < ${stop}) ? ${2 * Math.sign(l.walk)} : 0";
  rig.transform.scale.expression = "var f = timeToFrames(time) - ${l.s0}; [value[0], value[1] * (1 + Math.sin(f / 19) * 0.005)]";
  var hip = nul(${J("HIP " + l.name)}, ${a}, ${b}, [0, 0]); hip.setParentWithJump(rig); hip.transform.position.setValue([${-cx}, ${-y1}]);
  hip.transform.position.expression = "${lfE} value + [0, ${r2(Lg)} * (1 - Math.cos(th * Math.PI / 180))]";`);
    const part = (q, name, rotE) => {
      const f = copy(q.file);
      body.push(`  (function(){ var p = add(F(${J(f)}), ${a}, ${b}, ${J(name + " " + l.name)}); p.setParentWithJump(hip);
    p.transform.anchorPoint.setValue([${r2(q.pivot ? q.pivot[0] - q.x : 0)}, ${r2(q.pivot ? q.pivot[1] - q.y : 0)}]);
    p.transform.position.setValue([${r2(q.pivot ? q.pivot[0] : q.x)}, ${r2(q.pivot ? q.pivot[1] : q.y)}]); p.transform.scale.setValue([100, 100]);
    ${rotE ? `p.transform.rotation.expression = "${rotE}";` : ""} })();`);
    };
    legs.forEach((q) => part(q, `leg ${q.side}`, `${lfE} ${q.side === "L" ? "" : "-"}th`));
    arms.forEach((q) => part(q, `arm ${q.side}`, `${lfE} var f = timeToFrames(time) - ${l.s0}; walking ? ${q.side === "L" ? "-" : ""}th * 0.6 : Math.sin(f / 23 + ${q.side === "L" ? 0 : 2}) * 1.2`));
    part({ ...r.body, pivot: null }, "body", null);
    for (const hd of l.actorHeads ?? []) {
      // expression / talk / blink head: on only on its frames (hold keys); bobs with the breath, tilts about the chin
      const f = copy(hd.file);
      const [hx, hy, hw, hh] = hd.rect;
      const on = new Set(hd.frames);
      body.push(`  (function(){ var p = add(F(${J(f)}), ${a}, ${b}, ${J("head " + hd.file.split("/").pop() + " " + l.name)}); p.setParentWithJump(hip);
    p.transform.anchorPoint.setValue([${r2(hd.wh[0] / 2)}, ${r2(hd.wh[1])}]); p.transform.position.setValue([${r2(hx + hw / 2)}, ${r2(hy + hh)}]);
    p.transform.scale.setValue([${r2((hw / hd.wh[0]) * 100)}, ${r2((hh / hd.wh[1]) * 100)}]);
    
    p.transform.rotation.expression = "Math.sin((timeToFrames(time) - ${l.s0} + ${l.seed}) / 53) * 1.2";
    var op = p.transform.opacity;`);
      let prev = -1;
      for (let fr = a; fr < b; fr++) { const v = on.has(fr) ? 100 : 0; if (v !== prev) { body.push(`    key(op, ${fr}, ${v}, true);`); prev = v; } }
      body.push(`  })();`);
    }
    if (l.enter) body.push(`  // entrance from ${l.enter.from}: ${l.enter.frames} f`);
    body.push(`})();`);
  }
}
w(body.join("\n"));
// FX overlay above characters
for (const s of segs) w(`(function(){ var l = add(F("footage/FX/fx_0000.png", true), ${s.a}, ${s.b}, "FX ${s.a}"); l.transform.anchorPoint.setValue(${J(local(s.cam, 0, 0).map((v) => -v))}); l.transform.position.setValue([0,0]); ${parentTo("l", s.cam)} })();`);

// ---------- labels, captions, name cards (top) ----------
for (const l of L.layers.filter((q) => q.kind === "label" || q.kind === "cap" || q.kind === "card").sort((p, q) => p.z - q.z)) {
  const [a, b] = l.win;
  if (l.kind === "label") {
    const bw = l.text.length * l.size * 0.66 + 60, bh = l.size * 1.75;
    const P = local(l.cam, l.x, l.y);
    w(`(function(){ var s = comp.layers.addShape(); s.name = ${J("LABEL " + l.text)}; s.inPoint = T(${a}); s.outPoint = T(${b});
  s.transform.anchorPoint.setValue([0,0]); ${parentTo("s", l.cam)} s.transform.position.setValue(${J(P)});
  var C = s.property("ADBE Root Vectors Group");
  ${l.to ? `var g0 = C.addProperty("ADBE Vector Group"); var c0 = g0.property("ADBE Vectors Group");
  var ln = c0.addProperty("ADBE Vector Shape - Group"); var sh = new Shape(); sh.vertices = [[0,0], ${J([r2(l.to[0] - l.x), r2(l.to[1] - l.y)])}]; sh.closed = false; ln.property("ADBE Vector Shape").setValue(sh);
  var dot = c0.addProperty("ADBE Vector Shape - Ellipse"); dot.property("ADBE Vector Ellipse Size").setValue([20,20]); dot.property("ADBE Vector Ellipse Position").setValue(${J([r2(l.to[0] - l.x), r2(l.to[1] - l.y)])});
  var st0 = c0.addProperty("ADBE Vector Graphic - Stroke"); st0.property("ADBE Vector Stroke Color").setValue(${J(INK)}); st0.property("ADBE Vector Stroke Width").setValue(8); st0.property("ADBE Vector Stroke Line Cap").setValue(2);
  var fl0 = c0.addProperty("ADBE Vector Graphic - Fill"); fl0.property("ADBE Vector Fill Color").setValue(${J(INK)});` : ""}
  var g = C.addProperty("ADBE Vector Group"); var c = g.property("ADBE Vectors Group");
  var r = c.addProperty("ADBE Vector Shape - Rect"); r.property("ADBE Vector Rect Size").setValue([${r2(bw)}, ${r2(bh)}]); r.property("ADBE Vector Rect Position").setValue([0, ${r2(-l.size + bh / 2)}]); r.property("ADBE Vector Rect Roundness").setValue(10);
  var st = c.addProperty("ADBE Vector Graphic - Stroke"); st.property("ADBE Vector Stroke Color").setValue(${J(INK)}); st.property("ADBE Vector Stroke Width").setValue(7);
  var fl = c.addProperty("ADBE Vector Graphic - Fill"); fl.property("ADBE Vector Fill Color").setValue(${J(hex(l.color))});
  g.property("ADBE Vector Transform Group").property("ADBE Vector Rotation").setValue(-3);
  var t = txt(${J(l.text)}, ${l.size}, ${J(INK)}, 0); t.name = ${J("LABEL TEXT " + l.text)}; t.inPoint = T(${a}); t.outPoint = T(${b});
  t.setParentWithJump(s); t.transform.position.setValue([0, ${r2(l.size * 0.32)}]); t.transform.rotation.setValue(-3);
  var sc = s.transform.scale; key(sc, ${l.at}, [0,0]); key(sc, ${l.at + 4}, [112,112]); key(sc, ${l.at + 7}, [100,100]); })();`);
  } else if (l.kind === "cap") {
    const y = l.pos === "top" ? 64 + l.size * 0.9 : H - 70 - l.size * 0.22;
    w(`(function(){ var t = txt(${J(l.text.toUpperCase())}, ${l.size}, [1,1,1], 4); t.name = ${J("CAPTION " + l.text)}; t.inPoint = T(${a}); t.outPoint = T(${b});
  t.transform.position.setValue([${W / 2}, ${r2(y)}]); shadow(t); })();`);
  } else {
    w(`(function(){ var s = comp.layers.addSolid([0,0,0], "CARD dim", ${W}, ${H}, 1); s.inPoint = T(${a}); s.outPoint = T(${b}); s.transform.opacity.setValue(70);
  var t = txt(${J(l.text.toUpperCase())}, 118, [1,1,1], 0); t.name = ${J("CARD " + l.text)}; t.inPoint = T(${a}); t.outPoint = T(${b}); t.transform.position.setValue([${W / 2}, ${l.sub ? 520 : 580}]); shadow(t);
  ${l.sub ? `var u = txt(${J(l.sub.toUpperCase())}, 50, [1,1,1], 0); u.name = "CARD sub"; u.inPoint = T(${a}); u.outPoint = T(${b}); u.transform.position.setValue([${W / 2}, 610]); u.transform.opacity.setValue(85); shadow(u);` : ""} })();`);
  }
}
w(`comp.openInViewer(); app.endUndoGroup();
alert("${compName} built: " + comp.numLayers + " layers.");
})();`);
fs.mkdirSync(pkg, { recursive: true });
fs.writeFileSync(path.join(pkg, `${compName.replace(/[^A-Za-z0-9]+/g, "_")}.jsx`), out.join("\n"));
console.log("jsx written", L.layers.length, "layers", L.sfx.length, "sfx", segs.length, "plate segments");
